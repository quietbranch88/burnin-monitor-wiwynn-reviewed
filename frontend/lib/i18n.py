def lang() -> str:
    return st.session_state.get(LANG_KEY, "en")  # until the admin's choice has been read


def t(text: str, **values: object) -> str:
    """`text` in the chosen language, with `values` filled in."""
    out = ZH.get(text, text) if lang() == "zh" else text
    return out.format(**values) if values else out


# Role names as shown: the API's "user" role is the test engineer.
ROLE_NAMES = {"admin": "Administrator", "user": "Engineer", "viewer": "Viewer"}


def role_name(role: str) -> str:
    return t(ROLE_NAMES.get(role, role))


def use(language: str | None) -> None:
    """Show this session in the admin's language; keep the last one if it could not be read."""
    if language in LANGUAGES:
        st.session_state[LANG_KEY] = language


# The API's messages stay as it sends them (English). The Chinese interface puts a Chinese line
# for the HTTP status in front: statuses are the API's documented contract (docs/DESIGN.md,
# "API errors"), while matching its English texts here broke silently whenever one changed.
STATUS_ZH: dict[int, str] = {
    400: "請求格式有誤",
    401: "登入已失效，請重新登入",
    403: "你的角色不能執行這個動作",
    404: "找不到這筆資料",
    409: "與現有資料衝突",
    413: "檔案太大",
    422: "輸入的資料有誤",
    429: "請求太頻繁，請稍後再試",
    500: "系統發生錯誤，請稍後再試",
    503: "服務暫時無法使用，請稍後再試",
}


def api_message(status: int, text: str) -> str:
    """An error from the API as shown: in Chinese, the status in Chinese and then the API's own words."""
    if lang() != "zh" or status not in STATUS_ZH:
        return text
    return f"{STATUS_ZH[status]}：{text}" if text else STATUS_ZH[status]
